//! Мигающая каретка ввода.
//!
//! Framebuffer-консоль была write-only: текст шёл вниз, а позиция *логического*
//! курсора внутри строки была невидима, так что правка в середине строки
//! выглядела применённой в конце. Этот модуль делает каретку реальным видимым
//! объектом, рисуемым в клетке, которую займёт следующий набранный символ.
//!
//! Это возможно благодаря трём фактам, и все три несущие:
//!
//! * Консоль держит **клеточную модель** напечатанного, поэтому клетку можно
//!   перекрасить без перепечатки строки (`FramebufferWriter::paint_cell`).
//! * Покраска клетки **не двигает курсор консоли**, поэтому стирание каретки
//!   не уводит консоль вперёд и не прокручивает её.
//! * Консоль сообщает **где она**, после печати буфера, поэтому клетка каретки
//!   выводится проходом *назад* на число символов после логического курсора.
//!   Именно это делает каретку в середине строки точной, а не приблизительной.
//!
//! Каретка — вертикальная полоса в левом пиксельном столбце клетки, не блок:
//! блок скрывает символ под собой, а каретка должна показывать, куда пойдёт
//! текст, а не заменять то, что уже есть.
use crate::drivers::framebuffer;
use crate::shell::editor::LineEditor;

/// Цвет каретки: cyan (`0x00FFFF`), намеренно отличный от зелёного промпта
/// (R8.3) и белого текста по умолчанию, чтобы она не читалась как часть ни
/// того, ни другого.
pub const CARET_COLOR: u32 = 0x00FFFF;

/// Каретка включена первую половину периода и выключена вторую, так что
/// мигание симметрично, а его частота не зависит от того, как часто цикл shell
/// возвращается.
const BLINK_PERIOD_MS: u64 = 600;

/// Высота полосы каретки в пикселях из 16-пиксельной клетки. Короче глифов,
/// чтобы полоса читалась как точка вставки, а не нарисованная рамка.
const CARET_BAR_H: usize = 12;

/// Первая и последняя клетки одной строки консоли, в абсолютных координатах
/// сетки. Производит shell (он один знает, куда напечатана строка ввода),
/// потребляет select-all, так что все пользователи этих строк согласованы.
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub struct CellRangeCells {
    pub first: Cell,
    pub last: Cell,
}

/// Клетка сетки `(col, row)` текстовой консоли.
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub struct Cell {
    pub col: usize,
    pub row: usize,
}

/// Где каретка сейчас и нарисована ли она.
///
/// У shell одна такая на весь сеанс: она должна стирать каретку **в той
/// клетке, где была нарисована**, а каретка, стёртая где-то ещё, оставляет
/// лишнюю полосу, поэтому клетку нельзя пересчитать с нуля в момент стирания.
pub struct Caret {
    cell: Option<Cell>,
    drawn: bool,
}

impl Caret {
    pub const fn new() -> Self {
        Caret {
            cell: None,
            drawn: false,
        }
    }

    /// Клетка для каретки `editor` по клетке курсора консоли **после**
    /// печати буфера и числу колонок консоли.
    ///
    /// Консоль только что напечатала `prompt + buffer`, поэтому её курсор стоит
    /// на клетку после последнего символа буфера; символы после логического
    /// курсора — это `len - cursor`, и каретка находится на столько клеток
    /// назад. Это точно, а не приблизительно — в том числе в середине строки,
    /// после переноса строки или прокрутки консоли, потому что это разность
    /// двух позиций, а не абсолютная строка.
    ///
    /// Возвращает `None` для сетки, которая не вмещает каретку (нет
    /// framebuffer, нулевое число колонок или проход назад уходит за верх
    /// сетки), так что вызывающие просто пропускают рисование.
    pub fn cell_for(
        console_cell: (usize, usize),
        editor: &LineEditor,
        cols: usize,
    ) -> Option<Cell> {
        if cols == 0 {
            return None;
        }
        let trailing = editor
            .buffer()
            .chars()
            .count()
            .saturating_sub(editor.cursor());
        let (col, row) = console_cell;
        let end = row * cols + col;
        let start = end.checked_sub(trailing)?;
        Some(Cell {
            col: start % cols,
            row: start / cols,
        })
    }

    /// Переместить каретку в `cell`, рисуя или стирая по необходимости, и
    /// вернуть, видима ли она сейчас.
    ///
    /// Сначала стереть, затем нарисовать, никогда наоборот: покидаемая клетка
    /// восстанавливается из модели самой консоли, так что символ под старой
    /// кареткой не остаётся замазанным.
    pub fn place(&mut self, cell: Cell, on: bool) -> bool {
        if self.cell != Some(cell) {
            self.erase();
            self.cell = Some(cell);
        }
        self.set_visible(on);
        self.drawn
    }

    /// Фаза мигания для текущего тика: включена первую половину каждого периода.
    ///
    /// `ticks` — millisecond-счётчик тиков планировщика (`TICK_HZ` = 1000), так
    /// что период выражается прямо в миллисекундах и не зависит от частоты
    /// обновления консоли.
    pub fn blink_on(ticks: u64) -> bool {
        (ticks % BLINK_PERIOD_MS) < BLINK_PERIOD_MS / 2
    }

    /// Нарисовать или стереть каретку в текущей клетке. Идемпотентно: повтор
    /// того же состояния — no-op, так что можно вызывать на каждой итерации цикла.
    pub fn set_visible(&mut self, on: bool) {
        if self.drawn == on {
            return;
        }
        let Some(cell) = self.cell else {
            return;
        };
        framebuffer::console().paint_caret(cell.col, cell.row, on, CARET_COLOR, CARET_BAR_H);
        self.drawn = on;
    }

    /// Стереть каретку, если есть, и забыть, где она была.
    ///
    /// Вызывается до всего, что перепечатывает строку (`redraw_line`, новый
    /// промпт, список дополнений): каретка — оверлей поверх клетки, и текст,
    /// напечатанный поверх, унаследовал бы лишнюю полосу.
    pub fn erase(&mut self) {
        if let Some(cell) = self.cell {
            if self.drawn {
                framebuffer::console().paint_caret(
                    cell.col,
                    cell.row,
                    false,
                    CARET_COLOR,
                    CARET_BAR_H,
                );
            }
        }
        self.drawn = false;
    }

    /// Забыть каретку, не трогая пиксели, — когда экран очистили или прокрутили
    /// снаружи и ни одной клетке больше нельзя доверять.
    pub fn reset(&mut self) {
        self.cell = None;
        self.drawn = false;
    }
}

impl Default for Caret {
    fn default() -> Self {
        Self::new()
    }
}
