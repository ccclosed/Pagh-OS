// shell/cat.rs — чистое потоковое ядро команды `cat`
// 64-битное ядро ОС x86_64 на Rust (#![no_std])
//
// `commands::cmd_cat` — тонкий клей VFS + консоли; всё, что он решает, живёт
// здесь, чтобы in-kernel набор свойств (`src/test.rs`, `shell_prop_tests`)
// гонял точную байтовую последовательность, которую получает пользователь, без
// VFS и консоли:
//
// * чтение чанками по 256 байт, дословный вывод каждого байта по порядку;
// * остановка на EOF, на капе [`MAX_BYTES`] или на первой ошибке чтения;
// * завершение вывода на свежей строке: если что-то выведено и последний байт
//   не `\n`, вывести один. Без этого следующий промпт приклеивается к
//   последней строке файла (`hello-pagh:/>`), что портит любой транскрипт,
//   который читает человек или E2E-скрипт.

/// Кап байт: `cat` не должен крутиться вечно на бесконечном устройстве.
pub(crate) const MAX_BYTES: u64 = 64 * 1024;

/// Размер запроса на чтение. Мал намеренно: весь смысл streaming в том, что
/// `cat` никогда не буферизует файл, так что это стек, а не heap.
const CHUNK: usize = 256;

/// Что сделал один вызов [`stream`].
#[derive(Debug, PartialEq, Eq)]
pub(crate) struct Streamed {
    /// Байты файла, выведенные (смещение, на котором поток остановился).
    pub bytes: u64,
    /// Был ли добавлен завершающий `\n`, потому что последний выведенный байт
    /// им не был.
    pub newline_added: bool,
    /// Чтение вернуло ошибку после `bytes` выведенных байт.
    pub read_failed: bool,
}

/// Вывести файл через `write` до EOF / [`MAX_BYTES`] / ошибки чтения, затем
/// завершить вывод `\n`, если последний выведенный байт им ещё не является.
///
/// `read(offset, buf)` кладёт не более `buf.len()` байт в `buf`, возвращает
/// количество (`Ok(0)` — EOF) и `Err(())` при ошибке VFS; `write` получает
/// байты по порядку. Контракт точный, чтобы тест мог его проверить:
///
/// * выведенные байты — первые [`Streamed::bytes`] байт файла, с капом
///   [`MAX_BYTES`];
/// * пустой файл не даёт вывода вообще (и никакого newline);
/// * если выведен хотя бы один байт и последний не `b'\n'`, следом идёт ровно
///   один `b"\n"` — в том числе после ошибки чтения, чтобы сообщение об ошибке
///   вызывающего начиналось с собственной строки;
/// * вызывающий узнаёт об ошибке через [`Streamed::read_failed`] только после
///   вывода этого терминатора.
pub(crate) fn stream<R, W>(mut read: R, mut write: W) -> Streamed
where
    R: FnMut(u64, &mut [u8]) -> Result<usize, ()>,
    W: FnMut(&[u8]),
{
    let mut buf = [0u8; CHUNK];
    let mut bytes: u64 = 0;
    let mut last: Option<u8> = None;
    let mut read_failed = false;
    while bytes < MAX_BYTES {
        // Никогда не просить больше, чем позволяет кап, чтобы кап был точным.
        let want = ((MAX_BYTES - bytes).min(CHUNK as u64)) as usize;
        match read(bytes, &mut buf[..want]) {
            Ok(0) => break,
            Ok(n) => {
                // Защитно: сломанный `read` не должен индексировать за пределы запроса.
                let n = n.min(want);
                if n == 0 {
                    break;
                }
                write(&buf[..n]);
                last = Some(buf[n - 1]);
                bytes += n as u64;
            }
            Err(()) => {
                read_failed = true;
                break;
            }
        }
    }
    let newline_added = matches!(last, Some(b) if b != b'\n');
    if newline_added {
        write(b"\n");
    }
    Streamed {
        bytes,
        newline_added,
        read_failed,
    }
}
