// task/switch.rs — переключение контекста, трамплин ядерного потока, стаб IRQ таймера.

use core::arch::asm;

/// Кооперативное переключение контекста для *уже выполняющегося* потока (путь
/// `yield_current`).
///
/// # Инвариант единого сохранённого фрейма (Requirement 5.1)
///
/// Все три пути контекста — `kernel_thread_spawn` (начальный фрейм),
/// `yield_switch` (кооперативный) и `irq32_stub` (вытесняющий/тиковый) — создают
/// и потребляют **одну** раскладку сохранённого фрейма, поэтому задачу,
/// приостановленную ЛЮБЫМ путём, можно возобновить ЛЮБЫМ путём с точным
/// сохранением instruction pointer и stack pointer (Requirements 5.2, 5.3, 5.4).
///
/// Сохранённый фрейм, от младшего адреса к старшему (как его оставляет IRQ
/// таймера):
/// ```text
///   [rsp+0]    RFLAGS (для popfq, IF=0 — хвост восстановления идёт с выключенными прерываниями)
///   [+8..+120] r15,r14,r13,r12,r11,r10,r9,r8,rbp,rdi,rsi,rdx,rcx,rbx,rax
///   [+128]     RIP        (точка возобновления)
///   [+136]     CS         (селектор кода ядра)
///   [+144]     RFLAGS     (для iretq — возобновлённая задача сохраняет своё состояние IF)
///   [+152]     RSP        (ВСЕ фреймы: long-mode iretq всегда снимает SS:RSP)
///   [+160]     SS         (ВСЕ фреймы: long-mode iretq всегда снимает SS:RSP)
/// ```
///
/// # Requeue до восстановления
///
/// Путь структурно повторяет `irq32_stub`, а не только раскладку фрейма: после
/// сохранения фрейма он ВЫЗЫВАЕТ планировщик (`scheduler_yield_switch`) с
/// сохранённым RSP; планировщик ставит уступающую задачу в очередь ДО
/// переключения стека, как `scheduler_tick_irq` на вытесняющем пути, затем
/// возвращает сохранённый RSP следующей задачи для общего хвоста восстановления.
///
/// Прежняя реализация (`switch_context`) ставила уступающую задачу в очередь в
/// Rust-коде ПОСЛЕ переключения стека в inline-asm. Этот код выполнялся, только
/// когда задачу уже перепланировали — чего не могло случиться, потому что она
/// никогда не попадала в очередь (её сохранённый RSP жил лишь в локальной
/// переменной на её собственном, уже приостановленном стеке). Первая же
/// кооперативная уступка при непустой ready-очереди молча выкидывала уступающую
/// задачу из ротации навсегда.
///
/// # Long-mode IRETQ всегда снимает пять слов
///
/// В 64-битном режиме `iretq` безусловно потребляет RIP, CS, RFLAGS, RSP и SS —
/// даже когда CS остаётся ring0 (без смены привилегий); точно так же доставка
/// прерывания всегда кладёт все пять. Поэтому синтетические ring0-фреймы обязаны
/// включать слова RSP/SS: 3-словный фрейм заставлял восстанавливающий `iretq`
/// читать за вершиной стека ядра в неотображённую guard-область (page fault на
/// [stack_top] при первом восстановлении задачи). Тиковый путь работает лишь
/// потому, что CPU сам кладёт полный 5-словный фрейм на КАЖДОЕ прерывание в long
/// mode.
pub unsafe fn yield_switch() {
    // Селекторы ядра для синтезированного iretq-фрейма. Те же значения, что CPU
    // кладёт при прерывании на том же уровне привилегий и что
    // `kernel_thread_spawn` зашивает в начальный фрейм нового потока.
    let kernel_cs = crate::arch::x86_64::gdt::Selectors::kernel_code().0 as u64;
    let kernel_ss = crate::arch::x86_64::gdt::Selectors::kernel_data().0 as u64;

    asm!(
        // Long-mode iretq ВСЕГДА снимает SS:RSP (даже ring0 -> ring0), поэтому
        // синтезированный фрейм обязан их включать. rax здесь и ниже безопасно
        // использовать как царапину: clobber_abi("C") объявляет его
        // испорченным. Ни lea, ни push не трогают RFLAGS, поэтому pushfq ниже
        // всё ещё захватывает флаги вызывающего.
        "push r11",              // [+160] SS  (kernel data selector, pinned in("r11"))
        "lea rax, [rsp + 8]",    // RSP вызывающего на входе (над push'ем SS)
        "push rax",              // [+152] RSP (iretq restores the caller stack)
        // Захват IRET-RFLAGS: фиксирует состояние IF вызывающего (ядерные
        // потоки уступают с IF=1; обработчики syscall Linux могут уступать при
        // любом состоянии IF), чтобы `iretq` возобновил задачу с её собственным
        // состоянием прерываний. Этот pushfq ОБЯЗАН оставаться ДО `cli` ниже.
        "pushfq",                // [+144] RFLAGS (for iretq)
        // Инвариант слота popfq: IF=0 (зеркалит irq32_stub): сбросить IF
        // *после* захвата iret-RFLAGS, но *до* push'ей GPR и финального pushfq,
        // чтобы хвост восстановления ЛЮБОГО пути, возобновляющего этот фрейм,
        // шёл с выключенными прерываниями до `iretq`. Это же делает всю
        // критическую область save → scheduler → restore атомарной в
        // однопроцессорном дизайне. `sti` не нужен: `iretq` восстановит IF из
        // захваченного выше слота RFLAGS iret-фрейма.
        "cli",
        "push r10",              // [+136] CS  (kernel code selector, pinned in("r10"))
        // rax здесь свободен как царапина: clobber_abi("C") ниже уже объявляет
        // его испорченным (универсальный операнд `out(reg) _` несовместим с
        // clobber_abi). Последующий push GPR кладёт адрес метки в слот rax
        // фрейма, что по той же причине нормально.
        "lea rax, [rip + 2f]",
        "push rax",              // [+128] RIP  = resume label below
        // ── 15 GPR, rax первым … r15 последним (зеркало pop'ов восстановления) ──
        "push rax", "push rbx", "push rcx", "push rdx",
        "push rsi", "push rdi", "push rbp",
        "push r8", "push r9", "push r10", "push r11",
        "push r12", "push r13", "push r14", "push r15",
        "pushfq",                // [+0] RFLAGS (for popfq, IF=0) = lowest = saved RSP
        // ── Requeue до восстановления: передать сохранённый фрейм планировщику ──
        // scheduler_yield_switch(current_rsp) ставит эту задачу в очередь,
        // выбирает следующую (активируя её RSP0/FS-base и перезагружая CR3) и
        // возвращает её сохранённый RSP — либо `current_rsp` без изменений, когда
        // больше нечего запускать (тогда уступка — no-op восстановление нашего
        // собственного фрейма).
        "mov rdi, rsp",
        "and rsp, -16",          // SysV 16-byte alignment for the call
        "call {switch_fn}",
        "mov rsp, rax",
        // ── Восстановление: идентично хвосту irq32_stub ─────────────────
        "popfq",
        "pop r15", "pop r14", "pop r13", "pop r12",
        "pop r11", "pop r10", "pop r9", "pop r8",
        "pop rbp", "pop rdi", "pop rsi", "pop rdx",
        "pop rcx", "pop rbx", "pop rax",
        "iretq",
        // Точка возобновления: задача, сохранённая этим (или любым) путём,
        // попадает сюда через iretq с восстановленным в исходное значение RSP;
        // затем управление выходит из asm-блока, и функция возвращается к
        // вызывающему.
        "2:",
        // Исправление #GP на foreground-ожидании: эти значения ОБЯЗАНЫ быть
        // привязанными регистрами. С универсальным `in(reg)` аллокатор мог
        // выбрать RAX — clobber_abi("C") НЕ исключает ABI-clobbered регистры из
        // распределения операндов, лишь пропускает добавление clobbers для уже
        // занятых операндами. Когда kcs попадал в RAX, царапина
        // `lea rax, [rsp + 8]` выше перезаписывала его до push'а: слот CS
        // получал копию caller-RSP, и восстанавливающий `iretq` падал с
        // #GP(err = rsp & ~3). R10/R11 этим asm до их push'ей не трогаются. Блок
        // GPR ниже кладёт значения селекторов в слоты r10/r11 фрейма — нормально:
        // оба caller-saved и уже объявлены испорченными.
        in("r10") kernel_cs,
        in("r11") kernel_ss,
        switch_fn = sym crate::task::scheduler::scheduler_yield_switch,
        clobber_abi("C"),
    );
}

// ─── Трамплин ядерного потока ────────────────────────────────────────────

extern "C" {
    pub fn kernel_thread_trampoline() -> !;
}

core::arch::global_asm!(
    ".global kernel_thread_trampoline",
    "kernel_thread_trampoline:",
    // Точка входа приходит в RDI через восстановление GPR в irq32_stub
    // (начальный фрейм `kernel_thread_spawn` кладёт `entry` в слот rdi). `iretq`
    // уже поставил RSP = stack_top, поэтому стек — чистая вершина стека этого
    // потока; `pop` не нужен (он прочитал бы мусор над фреймом — ошибка первого
    // bring-up).
    "    sti",
    "    call rdi", // rdi = entry; pushes return addr within the stack
    "    jmp scheduler_exit_thread",
);

/// Завершившийся ядерный поток паркуется здесь после возврата из точки входа
/// (`kernel_thread_trampoline` прыгает сюда по имени). Пометка pid как
/// exiting позволяет следующему тику снять его из ротации вместо requeue —
/// прежний цикл `sti; hlt; jmp` бесконечно возвращал мёртвый фрейм в очередь
/// каждый раунд.
#[no_mangle]
pub extern "C" fn scheduler_exit_thread() -> ! {
    crate::task::scheduler::kernel_thread_finished();
    // Парковка С ВКЛЮЧЁННЫМИ ПРЕРЫВАНИЯМИ. Прежняя последовательность
    // `cli` + `hlt` останавливала CPU с замаскированными прерываниями в момент
    // возврата любого ядерного потока (первым это ловил провижининг загрузки),
    // и на одном ядре замораживала всю машину: ни таймера, ни планировщика, ни
    // шелла. С `sti; hlt` таймер продолжает тикать, а когда тик снимает эту
    // задачу, она больше никогда не восстанавливается.
    loop {
        crate::arch::cpu::enable_interrupts();
        crate::arch::cpu::halt();
    }
}

// ─── Стаб IRQ таймера (вытесняющее переключение контекста) ───────────────

extern "C" {
    pub fn irq32_stub();
    // Не вызывается из Rust — вызывается из global_asm-блока `irq32_stub`
    // (`call scheduler_tick_irq`), который вычисляет RSP следующей задачи. Decl
    // extern держит символ в области видимости для линковки inline asm.
    #[allow(dead_code)]
    fn scheduler_tick_irq(current_rsp: u64) -> u64;
}

core::arch::global_asm!(
    ".global irq32_stub",
    "irq32_stub:",
    // ── Вытесняющее переключение контекста (канонический путь) ───────────
    // На IRQ таймера CPU уже положил iret-фрейм [RIP, CS, RFLAGS, RSP, SS]
    // (сверху вниз). Затем мы кладём 15 GPR и слово RFLAGS для `popfq`. Порядок
    // сохранения ниже и порядок восстановления (pop) дальше — точные зеркала и
    // побайтно совпадают с начальным фреймом `kernel_thread_spawn`
    // (Requirement 11.1 / Property 7).
    //
    // Соответствие слот ↔ регистр (порядок записи 1..=15 в spawn == порядок push
    // здесь; восстановление снимает в обратном, r15 первым … rax последним):
    //   1=rax  2=rbx  3=rcx  4=rdx  5=rsi  6=rdi  7=rbp  8=r8
    //   9=r9  10=r10 11=r11 12=r12 13=r13 14=r14 15=r15
    // `kernel_thread_spawn` кладёт `entry` потока в слот **rdi** (6-й
    // записываемый), поэтому после 15 pop'ов ниже rdi == entry.
    //
    // Сохранить все GPR в фиксированном порядке (восстанавливаются в обратном)
    "    push rax",
    "    push rbx",
    "    push rcx",
    "    push rdx",
    "    push rsi",
    "    push rdi",
    "    push rbp",
    "    push r8",
    "    push r9",
    "    push r10",
    "    push r11",
    "    push r12",
    "    push r13",
    "    push r14",
    "    push r15",
    "    pushfq",
    // rdi = текущий RSP (arg1 для scheduler_tick_irq)
    // Сохранить его НУЖНО ДО выравнивания RSP
    "    mov rdi, rsp",
    "    sub rsp, 8", // align to 16 (pushfq made it 8-off)
    "    call scheduler_tick_irq",
    // rax = новый RSP для восстановления
    "    mov rsp, rax",
    "    popfq",
    // Восстановить 15 GPR в обратном порядке push (r15 первым … rax последним).
    // Для только что созданного потока это оставляет rdi = entry; `iretq` затем
    // ставит RIP = kernel_thread_trampoline и RSP = stack_top.
    "    pop r15",
    "    pop r14",
    "    pop r13",
    "    pop r12",
    "    pop r11",
    "    pop r10",
    "    pop r9",
    "    pop r8",
    "    pop rbp",
    "    pop rdi",
    "    pop rsi",
    "    pop rdx",
    "    pop rcx",
    "    pop rbx",
    "    pop rax",
    "    iretq",
);
