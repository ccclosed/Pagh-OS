//! Обнаружение PAT и программирование `IA32_PAT` (MSR 0x277).
//!
//! Единственная привилегированная часть write-combined политики: CPUID и
//! `rdmsr`/`wrmsr`. Чистые правила (какие записи PAT ставить, какие PTE-биты
//! выбирают WC, fallback) живут в [`crate::memory::pat`] и проверяются на
//! хосте; здесь только «прочитать железо → позвать чистую функцию → записать
//! обратно».
//!
//! ## Что меняется и что нет
//!
//! Записи 4 и 5 `IA32_PAT` ставятся в WC (`0x01`), остальные шесть
//! сохраняются байт-в-байт. `CR0.CD` не трогается: это глобальный cache
//! disable, и его изменение сломало бы всю систему, а не только scanout.
//! `IA32_PAT` — MSR с полным 64-битным значением, поэтому пишется целиком.
//!
//! Программирование идёт один раз в начале boot, **до** первого
//! пользовательского отображения `/dev/fb0`: иначе лист мог бы сослаться на
//! entry 4, пока там ещё WB.

use crate::arch::cpu;
use crate::memory::pat;

/// Обнаружить PAT, запрограммировать WC-записи и зафиксировать результат для
/// [`pat::wc_supported`].
///
/// Безопасно вызывать один раз на boot-пути, когда прерывания ещё не
/// используются: запись MSR затрагивает только тип памяти для листьев,
/// ссылающихся на затронутые записи PAT.
pub fn init() {
    // SAFETY: CPUID — непривилегированная архитектурная инструкция без
    // побочных эффектов. Лист 1 существует на любом x86_64 (long mode
    // требует CPUID), поэтому обращение корректно и не может дать #UD.
    let leaf1 = unsafe { core::arch::x86_64::__cpuid(1) };
    if !pat::cpuid_supports_pat(leaf1.edx) {
        // Единственный лог fallback'а: дальше mmap/mprotect молча используют
        // прежнюю некешируемую пару, а не спамят на каждое отображение.
        pat::set_supported(false);
        crate::warn!("fb0: PAT missing, uncached");
        return;
    }

    let current = cpu::read_msr(pat::IA32_PAT);
    let target = pat::pat_msr_value(current);
    if target != current {
        // SAFETY: CPUID только что подтвердил наличие PAT, поэтому MSR 0x277
        // существует; меняются только записи 4/5 (WC), остальные сохранены,
        // CR0.CD не меняется. Запись идёт до первого WC-листа, так что ни
        // одно существующее отображение не меняет смысл задним числом.
        unsafe {
            cpu::write_msr(pat::IA32_PAT, target);
        }
    }
    pat::set_supported(true);
    // Тот же префикс `fb0: PAT`, что у fallback'а строкой выше: serial-гейт
    // ищет одно семейство маркеров, а не два разных.
    crate::info!(
        "fb0: PAT write-combining enabled (IA32_PAT 0x{:016x} -> 0x{:016x})",
        current,
        target
    );
}
