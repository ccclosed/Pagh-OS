//! Чистая политика пробуждения блокирующего чтения сокета.
//!
//! В этом ядре у сокетов и pipe нет очередей ожидания: `recvfrom`/`recvmsg`/
//! `read` на AF_UNIX крутят `yield_current()` и перечитывают байтовую очередь.
//! Пока очередь жива, это корректно, но у закрытия дескриптора во время такого
//! ожидания не было ни одного пути, который разбудил бы читателя:
//!
//!  * счётчики `readers`/`writers` (`src/task/fd.rs`) принадлежат ОБЩЕЙ очереди
//!    и уменьшаются только при уничтожении конца; локальный `Arc`, который
//!    держит сам syscall, очередь не отпускает, и `writers` остаётся > 0;
//!  * значит `PipeEndpoint::read` вечно отвечает `WouldBlock` — EOF не наступает
//!    никогда, хотя в таблице дескрипторов читающего процесса этого сокета уже
//!    нет (именно такую задачу и печатает watchdog: `stuck in syscall ? (nr=45
//!    arg0=0x3 closed)`).
//!
//! Поэтому на каждой уступке CPU перепроверяются два факта, и оба — чистые:
//! ссылается ли ещё ХОТЬ ОДИН дескриптор процесса на эту очередь (иначе
//! прочитать её больше некому — `EBADF`) и остались ли пишущие концы (иначе это
//! EOF — `Ok(0)`). Решение принимает [`wait_verdict`], чтобы политику можно было
//! проверить на хосте без compat-состояния и таблицы fd.
//!
//! Модуль — host-тестируемый шов, подключённый в `host-tests/src/lib.rs`
//! (свойство `p58`).

/// Что делать блокирующему чтению, если очередь не дала данных.
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum WaitVerdict {
    /// Очередь ещё может продвинуться: уступить CPU и перечитать.
    Continue,
    /// Пишущих концов не осталось — вернуть `Ok(0)` (EOF, как `close` пира).
    Eof,
    /// Читающий конец больше не принадлежит ни одному fd — вернуть `EBADF`.
    Ebadf,
}

/// Решение по двум наблюдаемым фактам.
///
/// `endpoint_referenced` — есть ли в таблице дескрипторов процесса хоть один
/// fd на эту очередь; `peer_writers` — число живых пишущих концов.
///
/// Порядок важен: сначала проверяется владение, потому что оставшийся «пишущий
/// конец» у осиротевшей очереди ничего не значит — данные в неё могут прийти, но
/// забрать их вызывающему больше нечем, и ожидание было бы вечным. Осиротевшая
/// очередь — `EBADF` даже при `peer_writers > 0`; живая, но без писателей —
/// EOF; всё остальное — ждать дальше.
pub fn wait_verdict(endpoint_referenced: bool, peer_writers: usize) -> WaitVerdict {
    if !endpoint_referenced {
        WaitVerdict::Ebadf
    } else if peer_writers == 0 {
        WaitVerdict::Eof
    } else {
        WaitVerdict::Continue
    }
}

// ─── Зеркало для блокирующей ЗАПИСИ ────────────────────────────────────────
//
// Тот же класс вечного зависания, но с другой стороны: `sendto`/`sendmsg`/
// `write` на ПОЛНОЙ очереди уступают CPU и перечитывают её. Если пишущий fd
// закрыли из соседнего потока, счётчики очереди не меняются (syscall держит
// `Arc`), и `write` вечно отвечает `WouldBlock` — watchdog печатал
// `stuck in syscall ? (nr=1 arg0=0x3 closed)`. Закрытие ЧИТАЮЩЕГО конца при
// этом чинится само: уничтожение последнего конца уменьшает `readers`, и
// следующая перезапись отвечает `Broken` (`EPIPE`) — поэтому политике остаётся
// ровно один вопрос: жив ли ещё хоть один дескриптор этой пишущей очереди.

/// Что делать блокирующему писателю, если очередь не приняла данные.
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum WriteVerdict {
    /// Пишущий конец ещё принадлежит таблице fd: уступить CPU и перезаписать.
    Continue,
    /// Ни один fd процесса больше не ссылается на пишущий конец — `EBADF`.
    Ebadf,
}

/// Решение по одному наблюдаемому факту — [`WriteVerdict`].
///
/// Порядок не нужен: `Broken` (`EPIPE`) распознаёт сама очередь, потому что
/// уничтожение читающего конца меняет её счётчик `readers`. Здесь остаётся
/// только осиротевший пишущий конец.
pub fn write_verdict(writer_referenced: bool) -> WriteVerdict {
    if writer_referenced {
        WriteVerdict::Continue
    } else {
        WriteVerdict::Ebadf
    }
}
