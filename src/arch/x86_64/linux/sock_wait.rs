//! Чистая политика ожидания блокирующего чтения/записи сокета.
//!
//! В этом ядре у сокетов и pipe нет очередей ожидания: `recvfrom`/`recvmsg`/
//! `read` на AF_UNIX перечитывают байтовую очередь. Раньше между перечитываниями
//! стоял `yield_current()`, то есть задача оставалась ГОТОВОЙ и немедленно
//! получала квант снова: на одном CPU это морило остальные задачи, а на каждом
//! витке брался глобальный compat-лок. Теперь ожидание — `sleep_ticks(1)`
//! (`hlt` до ближайшего тика; `apic::TICK_HZ = 1000`), поэтому процессор не
//! выедается, а пробуждение по данным приходит в пределах миллисекунды.
//!
//! Кроме сна политика решает три исхода, и все факты для них — чистые:
//!
//!  * закрытие дескриптора во время ожидания не имеет другого пути разбудить
//!    читателя: счётчики `readers`/`writers` (`src/task/fd.rs`) принадлежат
//!    ОБЩЕЙ очереди и уменьшаются только при уничтожении конца, а локальный
//!    `Arc`, который держит сам syscall, очередь не отпускает — `writers`
//!    остаётся > 0, EOF не наступает никогда, хотя в таблице дескрипторов
//!    читающего процесса этого сокета уже нет (watchdog: `stuck in syscall ?
//!    (nr=45 arg0=0x3 closed)`). Ссылается ли ещё хоть один fd процесса на
//!    очередь — [`read_step`]/[`write_step`] отвечают `EBADF`;
//!  * уничтожение последнего пишущего конца — EOF (`Ok(0)`);
//!  * истечение `SO_RCVTIMEO`/`SO_SNDTIMEO` — `EAGAIN`. Без этого `recv` висел
//!    вечно: Rust-std ставит там таймаут из `set_read_timeout`, а `poll()`
//!    живого PDP-клиента не возвращался и кадр после события не перерисовывался.
//!
//! Модуль — host-тестируемый шов, подключённый в `host-tests/src/lib.rs`
//! (свойства `p58` и `p60`).

/// Что делать блокирующему чтению, если очередь не дала данных.
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum WaitVerdict {
    /// Очередь ещё может продвинуться: уступить CPU и перечитать.
    Continue,
    /// Пишущих концов не осталось — вернуть `Ok(0)` (EOF, как `close` пира).
    Eof,
    /// Читающий конец больше не принадлежит ни одному fd — вернуть `EBADF`.
    Ebadf,
}

/// Решение по двум наблюдаемым фактам.
///
/// `endpoint_referenced` — есть ли в таблице дескрипторов процесса хоть один
/// fd на эту очередь; `peer_writers` — число живых пишущих концов.
///
/// Порядок важен: сначала проверяется владение, потому что оставшийся «пишущий
/// конец» у осиротевшей очереди ничего не значит — данные в неё могут прийти, но
/// забрать их вызывающему больше нечем, и ожидание было бы вечным. Осиротевшая
/// очередь — `EBADF` даже при `peer_writers > 0`; живая, но без писателей —
/// EOF; всё остальное — ждать дальше.
pub fn wait_verdict(endpoint_referenced: bool, peer_writers: usize) -> WaitVerdict {
    if !endpoint_referenced {
        WaitVerdict::Ebadf
    } else if peer_writers == 0 {
        WaitVerdict::Eof
    } else {
        WaitVerdict::Continue
    }
}

// ─── Ожидание: сон вместо busy-spin и SO_RCVTIMEO ───────────────────────────
//
// Очередей ожидания у планировщика нет: уступления бывают двух видов —
// `yield_current()` (задача остаётся готовой и немедленно получает квант снова,
// то есть КРУТИТСЯ: на одном CPU это морит остальные задачи и на каждом витке
// берёт глобальный compat-лок) и `sleep_ticks(1)` (`hlt` до ближайшего тика).
// Блокирующий ввод-вывод обязан спать вторым способом: тик LAPIC — 1 мс
// (`apic::TICK_HZ = 1000`), так что пробуждение по данным приходит в пределах
// одного тика, а CPU не выедается.
//
// Второе, что решает та же политика, — `SO_RCVTIMEO`: Rust-std ставит его
// (`set_read_timeout`) для `UnixStream::read`, и без честного таймаута
// `recv`/`recvfrom`/`read` висит вечно. Живой PDP-клиент (`pagh-files`) из-за
// этого не возвращался из `poll()`: он ЧИТАЛ события (байты доходили), но
// `poll` ждал вечного `read`, поэтому кадр после события не перерисовывался.
// Истечение таймаута — `EAGAIN` (`WouldBlock` у вызывающего), как в Linux.

/// Что делать блокирующему ЧТЕНИЮ, у которого очередь ответила `WouldBlock`.
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum ReadStep {
    /// Спать до следующего тика и перечитать очередь (не busy-spin).
    Sleep,
    /// `SO_RCVTIMEO` истёк — вернуть `EAGAIN`.
    TimedOut,
    /// Пишущих концов не осталось — `Ok(0)` (EOF, как `close` пира).
    Eof,
    /// Читающий конец больше не принадлежит ни одному fd — `EBADF`.
    Ebadf,
}

/// Что делать блокирующей ЗАПИСИ, у которой очередь полна.
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum WriteStep {
    /// Спать до следующего тика и переписать.
    Sleep,
    /// `SO_SNDTIMEO` истёк — вернуть `EAGAIN` (Linux: короткая запись/`EAGAIN`).
    TimedOut,
    /// Ни один fd процесса больше не ссылается на пишущий конец — `EBADF`.
    Ebadf,
}

/// Решение для блокирующего чтения: владение очередью, живые писатели и
/// истёкший таймаут.
///
/// Порядок — тот же, что у [`wait_verdict`] (владение, затем EOF), и таймаут
/// проверяется ПОСЛЕ них: закрытый пир — это `Ok(0)`, даже если `SO_RCVTIMEO`
/// уже истёк, иначе вызывающий принял бы нормальный конец потока за таймаут.
/// Истечение таймаута при живых данных не рассматривается вовсе: вызывающий
/// спрашивает эту политику только после `WouldBlock`.
pub fn read_step(referenced: bool, peer_writers: usize, timed_out: bool) -> ReadStep {
    match wait_verdict(referenced, peer_writers) {
        WaitVerdict::Ebadf => ReadStep::Ebadf,
        WaitVerdict::Eof => ReadStep::Eof,
        WaitVerdict::Continue if timed_out => ReadStep::TimedOut,
        WaitVerdict::Continue => ReadStep::Sleep,
    }
}

/// Решение для блокирующей записи: владение пишущим концом и истёкший таймаут.
///
/// Порядок: сначала владение (fd закрыли из соседнего потока — ждать больше
/// некому), только потом таймаут.
pub fn write_step(writer_referenced: bool, timed_out: bool) -> WriteStep {
    match write_verdict(writer_referenced) {
        WriteVerdict::Ebadf => WriteStep::Ebadf,
        WriteVerdict::Continue if timed_out => WriteStep::TimedOut,
        WriteVerdict::Continue => WriteStep::Sleep,
    }
}

/// `struct timeval` из `setsockopt(SO_RCVTIMEO|SO_SNDTIMEO)` → миллисекунды.
///
/// `Some(0)` — «ждать вечно» (Linux снимает таймаут нулевым timeval), `None` —
/// `EINVAL` (отрицательный компонент). Дробные миллисекунды округляются ВВЕРХ:
/// `tv_usec = 1` обязан остаться ненулевым таймаутом, иначе просьба вызывающего
/// превратилась бы в противоположную — вечное ожидание.
pub fn timeout_ms_from_timeval(sec: i64, usec: i64) -> Option<u64> {
    if sec < 0 || usec < 0 {
        return None;
    }
    Some(
        (sec as u64)
            .saturating_mul(1000)
            .saturating_add((usec as u64 + 999) / 1000),
    )
}

/// Дедлайн `SO_RCVTIMEO`/`SO_SNDTIMEO` в тиках планировщика.
///
/// `None` — таймаут не задан (ждём бесконечно). `Some(start, span)` — начальный
/// тик и длительность; сравнение идёт через `wrapping_sub`, поэтому
/// астрономическое переполнение счётчика тиков ожидание не ломает (иначе
/// `deadline < now` навсегда).
pub struct Deadline {
    start: u64,
    span: u64,
}

impl Deadline {
    /// Завести дедлайн по длительности в тиках (`0` — без таймаута).
    ///
    /// Миллисекунды в тики переводит вызывающий (`apic::ms_to_ticks`): этот
    /// модуль остаётся `core`-only, чтобы его исполнял host-тест.
    pub fn from_ticks(timeout_ticks: u64, now: u64) -> Option<Self> {
        if timeout_ticks == 0 {
            None
        } else {
            Some(Self {
                start: now,
                // Любой ненулевой таймаут — хотя бы один тик, иначе он истёк бы
                // мгновенно и `recv` возвращал бы `EAGAIN` не ожидая.
                span: timeout_ticks.max(1),
            })
        }
    }

    /// Истёк ли таймаут к тику `now`.
    pub fn expired(&self, now: u64) -> bool {
        now.wrapping_sub(self.start) >= self.span
    }
}

// ─── Зеркало для блокирующей ЗАПИСИ ────────────────────────────────────────
//
// Тот же класс вечного зависания, но с другой стороны: `sendto`/`sendmsg`/
// `write` на ПОЛНОЙ очереди уступают CPU и перечитывают её. Если пишущий fd
// закрыли из соседнего потока, счётчики очереди не меняются (syscall держит
// `Arc`), и `write` вечно отвечает `WouldBlock` — watchdog печатал
// `stuck in syscall ? (nr=1 arg0=0x3 closed)`. Закрытие ЧИТАЮЩЕГО конца при
// этом чинится само: уничтожение последнего конца уменьшает `readers`, и
// следующая перезапись отвечает `Broken` (`EPIPE`) — поэтому политике остаётся
// ровно один вопрос: жив ли ещё хоть один дескриптор этой пишущей очереди.

/// Что делать блокирующему писателю, если очередь не приняла данные.
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum WriteVerdict {
    /// Пишущий конец ещё принадлежит таблице fd: уступить CPU и перезаписать.
    Continue,
    /// Ни один fd процесса больше не ссылается на пишущий конец — `EBADF`.
    Ebadf,
}

/// Решение по одному наблюдаемому факту — [`WriteVerdict`].
///
/// Порядок не нужен: `Broken` (`EPIPE`) распознаёт сама очередь, потому что
/// уничтожение читающего конца меняет её счётчик `readers`. Здесь остаётся
/// только осиротевший пишущий конец.
pub fn write_verdict(writer_referenced: bool) -> WriteVerdict {
    if writer_referenced {
        WriteVerdict::Continue
    } else {
        WriteVerdict::Ebadf
    }
}
