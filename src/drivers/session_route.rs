//! Чистая маршрутизация «задача → консольная сессия» (host-tested).
//!
//! Ядро держит несколько консольных экземпляров: сессия 0 — boot/shell-консоль
//! (Limine scanout), сессии `1..MAX_SESSIONS` — offscreen-поверхности
//! терминальных окон desktop'а. Каждый вызов консольного I/O (печать, `with`,
//! `flush`, чтение скан-кода, `cwd`) обязан разрешить, чей экземпляр он трогает,
//! и делать это **без блокировок**: `fb_print!` зовётся из самых разных мест, в
//! том числе под спинлоками соседних подсистем.
//!
//! Поэтому решение вынесено в чистую функцию над снимком: владельцы сессий
//! (pid'ы их kernel-задач) и необязательная привязка pid→сессия для
//! Linux-compat-детей сессии (программа, запущенная `lxrun` в окне, — отдельная
//! задача, но её вывод принадлежит окну). Эффектный модуль
//! [`super::session`] кормит эту функцию атомиками, а сам источник остаётся
//! `core`-only и проверяется host-свойством P66.

/// Сколько всего консольных сессий поддерживает ядро, включая boot-сессию 0.
///
/// Boot-сессия плюс три терминальных окна. Число — граница массивов писателей,
/// курсоров и поверхностей, а не политика: каждое окно получает свой слот
/// (`/dev/vtfb{N}`/`vtinput{N}`/`vtmouse{N}`, `session`, `offscreen`,
/// `framebuffer::WRITERS`), поэтому два открытых терминала не делят экран, ввод
/// и scrollback. Четвёрка — компромисс: desktop реально запускает два-три окна,
/// а каждая сессия держит полный кадр экрана (offscreen) и свою задачу.
pub const MAX_SESSIONS: usize = 4;

/// Индекс boot-сессии: единственная сессия, которая рисует на реальный экран.
pub const BOOT_SESSION: usize = 0;

/// Разрешить, в какую сессию маршрутизировать I/O задачи `pid`.
///
/// Приоритет:
/// 1. `pid` — собственная задача сессии `s >= 1` (её pid записан владельцем):
///    возвращается `s`. Владелец сильнее привязки: задача сессии не может быть
///    перенаправлена в чужое окно даже ошибочной записью в таблицу привязок.
/// 2. `bind` (pid → сессия, для compat-детей) в пределах `MAX_SESSIONS` —
///    возвращается он.
/// 3. Иначе — [`BOOT_SESSION`].
///
/// `owners` индексируется номером сессии, поэтому `owners[0]` не читается:
/// у boot-сессии нет pid-владельца, она существует всегда.
pub fn route(pid: u64, owners: &[u64; MAX_SESSIONS], bind: Option<u64>) -> usize {
    if pid != 0 {
        for (session, owner) in owners.iter().enumerate().skip(1) {
            if *owner != 0 && *owner == pid {
                return session;
            }
        }
    }
    match bind {
        Some(session) if (session as usize) < MAX_SESSIONS => session as usize,
        _ => BOOT_SESSION,
    }
}
