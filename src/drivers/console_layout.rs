//! Геометрия текстовой сетки консоли: сколько клеток `8×18` помещается на экране.
//!
//! Чистый `core`-модуль без состояния и без пиксельного кода, поэтому host-тесты
//! исполняют ровно тот исходник, который компилирует ядро.
//!
//! ## Почему геометрия выводится из экрана
//!
//! Раньше сетка была **фиксированной** — `CHARS_PER_LINE=100` и `MAX_LINES=37`
//! «независимо от разрешения», — а `text_rows()` клампилась к `MAX_LINES`.
//! Модель и поверхность `/dev/vtconsole0` (`vtsurface::geometry`) уже считались
//! от экрана, поэтому на большом 16:9 дисплее они расходились: консоль, каретка и
//! mouse-выделение занимали только левые `100·8 = 800` px и верхние
//! `37·18 = 666` px. На 2560×1440 выделение мышью доходило до 46% высоты
//! экрана — «только до середины», — а на 1920×1080 до 62%; справа незанятой
//! оставалась ещё большая доля. Теперь число клеток выводится из реального
//! разрешения framebuffer'а (как у fbcon), и сетка консоли совпадает с геометрией
//! VT-поверхности.

/// Ширина клетки консольного шрифта (Fira Code, офлайн-растр `tools/gen_font.py`).
pub const CHAR_WIDTH: usize = 8;
/// Высота глиф-клетки в пикселях.
pub const CHAR_HEIGHT: usize = 18;
/// Высота нижней строки статуса: ровно одна клетка.
pub const STATUS_BAR_HEIGHT: usize = CHAR_HEIGHT;

/// Верхняя граница сетки — та же, что у ABI `/dev/vtconsole0`
/// (`vt_abi::MAX_COLS`/`MAX_ROWS`): поверхность обязана уметь опубликовать любую
/// сетку, которую построила консоль, и наоборот. 1000×1000 клеток — это ~5 МиБ
/// модели на писателя; реальные экраны (8K: 960×239 при этом шрифте) остаются
/// заметно ниже.
pub const MAX_COLS: usize = 1000;
/// См. [`MAX_COLS`].
pub const MAX_ROWS: usize = 1000;

/// Сколько колонок и строк реально помещается на экране `width`×`height`.
///
/// * колонки — `width / CHAR_WIDTH`;
/// * строки — `(height - STATUS_BAR_HEIGHT) / CHAR_HEIGHT`: полоса статуса
///   занимает собственную строку внизу экрана и не должна перекрывать текст;
/// * обе величины не меньше 1 (крошечный или ещё не поднятый экран) и не больше
///   [`MAX_COLS`]/[`MAX_ROWS`].
///
/// Сетка покрывает экран настолько, насколько это возможно целыми клетками:
/// остаток меньше одной клетки по каждой оси — обычный край экрана, а не
/// потерянное место.
pub fn console_grid(width: usize, height: usize) -> (usize, usize) {
    let cols = (width / CHAR_WIDTH).clamp(1, MAX_COLS);
    let rows = (height.saturating_sub(STATUS_BAR_HEIGHT) / CHAR_HEIGHT).clamp(1, MAX_ROWS);
    (cols, rows)
}

/// Клетка консоли под пикселем `(x, y)`, зажатая в сетку `cols`×`rows`.
///
/// Указатель может стоять на полосе статуса (ниже текстовой сетки) или за правым
/// краем: «последняя клетка» — это то, что пользователь визуально выделяет, а не
/// `row = y / CHAR_HEIGHT`, вылезший за модель. Без зажима строка вне сетки
/// подменялась последней при чтении (`read_row`), и копирование выделения
/// дублировало её текст.
pub fn cell_at(x: usize, y: usize, cols: usize, rows: usize) -> (usize, usize) {
    let col = (x / CHAR_WIDTH).min(cols.saturating_sub(1));
    let row = (y / CHAR_HEIGHT).min(rows.saturating_sub(1));
    (col, row)
}
