//! 8042 (i8042) controller drain — the single reader of the PS/2 byte stream.
//!
//! ПОЧЕМУ ОТДЕЛЬНЫЙ МОДУЛЬ. PS/2-байты приходят в один общий выходной буфер
//! 8042, а «чей это байт» говорит только бит 5 статусного порта (AUXDATA:
//! 1 = мышь, 0 = клавиатура). До сих пор IRQ1 читал ровно один байт и отдавал
//! его `ps2_kbd`, IRQ12 — один байт и `ps2_mouse`. Под нагрузкой это теряет
//! ввод: если распаковка пакета держит прерывания замаскированными десятками
//! миллисекунд, драйвер успевает прочитать **один** байт за окно, тогда как
//! мышь ставит в очередь 3–4 байта каждые 10 мс. Очередь 8042 (16 байт в
//! QEMU) переполняется, новые байты отбрасываются, поток пакетов рвётся — и
//! курсор «замерзает», хотя композитор продолжает рисовать кадры. Замер
//! (`.cache/pagh-agent-notes/qbug1.md`): во время `ppkg install` счётчик
//! принятых aux-байт не двигался десятки секунд, а compositor выдавал 15–20 fps.
//!
//! ЧТО ДЕЛАЕТ ЭТОТ МОДУЛЬ. `drain()` читает статус и выгребает **все** готовые
//! байты за один заход, маршрутизируя каждый по AUXDATA. Его зовут:
//!
//! * обработчики IRQ1/IRQ12 — быстрый путь, когда прерывания приходят;
//! * поток `inputd` — раз в тик. Это и есть страховка: `inputd` исполняется под
//!   нагрузкой (он же печатает диагностику), поэтому порт выгребается даже
//!   тогда, когда IRQ12 не успевает, — с периодом в один тик, а не «когда
//!   распаковка отдаст CPU».
//!
//! ПОЧЕМУ ПОД СПИНЛОКОМ. Задача (`inputd`) и IRQ-обработчик не должны делить
//! один байт: проверка «OBF установлен» и чтение DATA порта обязаны быть
//! атомарны относительно другого читателя. `Spinlock` маскирует IF на эту
//! пару, поэтому обработчик не может вклиниться между проверкой и чтением, а
//! задача не может отобрать байт у обработчика. Порядок байтов в очереди
//! `inputd` остаётся глобальным порядком 8042, маршрутизация — по AUXDATA.

use x86_64::instructions::port::Port;

use crate::sync::spinlock::Spinlock;

/// Статусный порт 8042 (только чтение).
const STATUS_PORT: u16 = 0x64;
/// Порто данных 8042: байты устройства → хост.
const DATA_PORT: u16 = 0x60;
/// Бит 0 статуса: выходной буфер полон (есть байт для чтения).
const STATUS_OBF: u8 = 0x01;
/// Бит 5 статуса: байт пришёл от AUX-устройства (мыши).
const STATUS_AUX: u8 = 0x20;
/// Предохранитель от зацикливания на сломанном/виртуальном контроллере.
const MAX_BYTES: usize = 64;

/// Сериализует «проверить OBF → прочитать DATA» между IRQ и `inputd`.
static PORT_LOCK: Spinlock<()> = Spinlock::new(());

/// Прочитать статус 8042.
///
/// SAFETY: чтение порта 0x64 — стандартный доступ к статусу 8042; побочных
/// эффектов у чтения нет (это не команда).
fn status() -> u8 {
    unsafe { Port::<u8>::new(STATUS_PORT).read() }
}

/// Прочитать байт данных 8042.
///
/// SAFETY: вызывается только когда статус сообщил OBF, то есть байт готов;
/// чтение 0x60 снимает его из выходного буфера.
fn data() -> u8 {
    unsafe { Port::<u8>::new(DATA_PORT).read() }
}

/// Выгрести все готовые байты 8042, не возвращаясь в прерванный код между ними.
///
/// Возвращает число прочитанных байт (для диагностики/тестов).
fn drain_locked() -> usize {
    let mut read = 0usize;
    while read < MAX_BYTES {
        let st = status();
        if st & STATUS_OBF == 0 {
            break;
        }
        let byte = data();
        read += 1;
        if st & STATUS_AUX != 0 {
            crate::drivers::inputd::push_aux(byte);
        } else {
            // Клавиатурный байт идёт через тот же разбор ^C/^Z, что и раньше:
            // маршрутизация байта по AUXDATA не должна менять семантику IRQ1.
            crate::drivers::ps2_kbd::handle_byte(byte);
        }
    }
    read
}

/// Выгрести 8042 из IRQ-контекста (IRQ1 или IRQ12).
///
/// IF уже замаскирован входом в обработчик; спинлок дополнительно закрывает
/// гонку с `inputd::poll` (та маскирует IF на время чтения, поэтому обработчик
/// не может вклиниться в её пару «статус → данные», и наоборот).
pub fn irq_drain() {
    let _serial = PORT_LOCK.lock();
    drain_locked();
}

/// Страховочный опрос из потока `inputd` (обычный контекст задачи).
///
/// Под нагрузкой IRQ12 может не исполняться десятки миллисекунд; `inputd`
/// исполняется каждый тик, поэтому этот вызов гарантирует, что порт не стоит
/// полным, пока идёт распаковка. Быстрый путь: если OBF=0, спинлок берётся
/// ровно на одно чтение статуса и сразу отпускается.
pub fn poll() {
    if status() & STATUS_OBF == 0 {
        return;
    }
    let _serial = PORT_LOCK.lock();
    drain_locked();
}
