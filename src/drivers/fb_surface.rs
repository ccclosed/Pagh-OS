//! Чистая арифметика пиксельной поверхности (host-tested).
//!
//! Размеры/шаг/страницы offscreen-поверхности терминальной сессии и разбиение
//! прямоугольника на куски «внутри одной 4 KiB страницы» — это единственная
//! часть [`super::offscreen`], которую можно проверить на хосте: сам модуль
//! поверхности аллоцирует кадры PMM и пишет через HHDM, то есть требует ядра.
//!
//! Здесь нет ни `unsafe`, ни состояния: `core`-only, поэтому host-свойство P66
//! исполняет ровно тот исходник, который компилирует ядро.

/// Размер страницы, которой ядро раздаёт пиксельные буферы (кадры PMM).
pub const PAGE: usize = 4096;

/// Геометрия поверхности: пиксели, шаг строки и число страниц.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct Geometry {
    /// Ширина в пикселях.
    pub width: usize,
    /// Высота в пикселях.
    pub height: usize,
    /// Байт на строку (шаг): `width * bpp`, без выравнивания — поверхность
    /// копирует раскладку boot-экрана, а не выбирает свою.
    pub stride: usize,
    /// Байт на пиксель (3 или 4).
    pub bpp: usize,
    /// Полный размер поверхности в байтах: `stride * height`.
    pub total_bytes: usize,
    /// Сколько страниц нужно, чтобы покрыть `total_bytes`.
    pub pages: usize,
}

/// Посчитать геометрию; `None`, если размеры/формат невозможны.
///
/// `bpp` ограничен 3..=4: консоль и редакторы рисуют XRGB-пиксели, а `flush`
/// копирует ровно `bpp` байт на пиксель. Нулевые размеры отвергаются, потому что
/// поверхность без пикселей нечего публиковать, а `stride * height` обязан
/// влезть в `usize` (иначе `mmap`/`read` отдали бы клиенту заведомо неверную
/// длину).
pub fn geometry(width: usize, height: usize, bpp: usize) -> Option<Geometry> {
    if width == 0 || height == 0 || !(3..=4).contains(&bpp) {
        return None;
    }
    let stride = width.checked_mul(bpp)?;
    let total_bytes = stride.checked_mul(height)?;
    let pages = total_bytes.div_ceil(PAGE);
    Some(Geometry {
        width,
        height,
        stride,
        bpp,
        total_bytes,
        pages,
    })
}

/// Разбить запрос `[offset, offset + len)` на кусок внутри одной страницы.
///
/// Возвращает `(индекс_страницы, смещение_внутри_страницы, длина_куска)`.
/// Вызывающий копирует кусок и повторяет с `offset + длина`; так линейный
/// прямоугольник ложится в набор физических кадров, которые не обязаны быть
/// смежными. `len == 0` даёт нулевой кусок — вызывающий не должен его
/// обрабатывать (это и есть условие выхода цикла).
///
/// Функция чистая: `chunk_at` с любым `offset` не пересекает границу страницы,
/// поэтому «кусок» никогда не потребует двух кадров.
pub fn chunk_at(offset: usize, len: usize) -> (usize, usize, usize) {
    let page = offset / PAGE;
    let in_page = offset % PAGE;
    let room = PAGE - in_page;
    (page, in_page, len.min(room))
}
