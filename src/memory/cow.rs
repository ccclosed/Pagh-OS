// memory/cow.rs — учёт владения кадрами copy-on-write.
//
// Модуль намеренно использует только `core` + `alloc` (без paging и локов):
// `host-tests` подключает его через `#[path]`, поэтому инвариант владения ниже
// проверяется на хосте свойствами по тому же исходнику, что компилирует ядро.
// `pmm.rs` оборачивает один [`CowRefs`] в свой спинлок.
//
// ## Инвариант
//
// Кадр, отображённый более чем в одном пользовательском адресном пространстве
// как COW-лист, несёт одну ссылку на каждое такое пространство. Кадр можно
// вернуть в битмап свободных только при освобождении ПОСЛЕДНЕЙ ссылки; до этого
// у каждого владельца есть живой PTE на него.
//
// `fork_user_space_cow` регистрирует шарящих (`acquire`), а каждый путь,
// отцепляющий COW-лист (`cow_copy_page`, `munmap`, `mprotect(PROT_NONE)`,
// замена через `MAP_FIXED`, снос адресного пространства), обязан вызвать
// `release` и освободить кадр только при возврате `true`. Пропуск этого вызова —
// use-after-free: кадр уходит в PMM, пока другое адресное пространство ещё
// отображает его на запись, и позже выдаётся как таблица страниц.

use alloc::collections::BTreeMap;

/// Архитектурный размер страницы — кадры индексируются выровненной базой.
const FRAME_SIZE: u64 = 4096;

/// Карта «COW-разделяемый кадр -> число ссылающихся адресных пространств».
///
/// Кадры появляются при fork и уходят при каждом отцеплении/копировании/сносе
/// листа. Кадры с единственным приватным владельцем НЕ отслеживаются: обычный
/// протокол alloc/free остаётся быстрым путём, а поиск по карте платят только
/// реально разделяемые кадры.
pub struct CowRefs {
    map: BTreeMap<u64, u32>,
}

impl CowRefs {
    /// Пустая таблица учёта (const, чтобы инициализировать статический спинлок).
    pub const fn new() -> Self {
        Self {
            map: BTreeMap::new(),
        }
    }

    /// Зарегистрировать одно адресное пространство как шарящего `frame`.
    /// Возвращает новое число ссылок. Адрес выравнивается по странице до
    /// индексации, поэтому вызывающий, передавший смещение (например,
    /// переведённый `virt_to_phys`), всё равно попадёт в ту же запись.
    pub fn acquire(&mut self, frame: u64) -> u32 {
        let e = self.map.entry(frame & !(FRAME_SIZE - 1)).or_insert(0);
        *e += 1;
        *e
    }

    /// Отпустить одного шарящего `frame`.
    ///
    /// Возвращает `true`, когда вызывающий ОБЯЗАН вернуть кадр в битмап
    /// свободных: это была последняя ссылка. `false`, пока хотя бы одно
    /// адресное пространство ещё отображает кадр.
    ///
    /// Кадр, отсутствующий в таблице, считается приватным (`true`):
    /// вызывающие приходят сюда только проверив COW-маркер PTE, поэтому
    /// неучтённый кадр означает уже потерянный учёт, и освобождение совпадает с
    /// прежним приватным путём. Каждый ядерный вызывающий обязан держать PTE,
    /// который сохраняет кадр живым в этом случае.
    pub fn release(&mut self, frame: u64) -> bool {
        let key = frame & !(FRAME_SIZE - 1);
        match self.map.get_mut(&key) {
            Some(1) => {
                self.map.remove(&key);
                true
            }
            Some(n) => {
                *n -= 1;
                false
            }
            None => true,
        }
    }

    /// Текущее число шарящих `frame` (0, когда кадр приватный/неучтённый).
    pub fn refs(&self, frame: u64) -> u32 {
        self.map
            .get(&(frame & !(FRAME_SIZE - 1)))
            .copied()
            .unwrap_or(0)
    }

    /// Число кадров, отслеживаемых сейчас как COW-разделяемые.
    pub fn tracked_frames(&self) -> usize {
        self.map.len()
    }
}

impl Default for CowRefs {
    fn default() -> Self {
        Self::new()
    }
}
