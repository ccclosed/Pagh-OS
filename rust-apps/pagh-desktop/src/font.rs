/// Глиф символа в ячейке 8×16 (1 бит на пиксель, старший бит левее).
///
/// ASCII берётся из [`FONT_8X16`], кириллица и типографские знаки — из
/// [`EXTRA_GLYPHS`]. Неизвестные символы ищутся как `?` (вызывающая сторона
/// сама решает, что делать).
pub fn glyph(ch: char) -> Option<&'static [u8; 16]> {
    let code = ch as u32;
    if (FIRST_CHAR as u32..=126).contains(&code) {
        return Some(&FONT_8X16[(code - FIRST_CHAR as u32) as usize]);
    }
    EXTRA_GLYPHS
        .binary_search_by_key(&ch, |(candidate, _)| *candidate)
        .ok()
        .map(|index| &EXTRA_GLYPHS[index].1)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn ascii_and_cyrillic_glyphs_exist() {
        assert!(glyph('A').is_some());
        assert!(glyph(' ').is_some());
        for ch in [
            'Д', 'о', 'м', 'а', 'ш', 'н', 'я', 'п', 'к', 'Ё', 'ё', '—', '…',
        ] {
            assert!(glyph(ch).is_some(), "нет глифа {ch:?}");
        }
        assert!(glyph('中').is_none());
    }

    #[test]
    fn cyrillic_glyphs_have_ink() {
        for ch in ['Д', 'о', 'я', 'Ё'] {
            let rows = glyph(ch).unwrap();
            assert!(rows.iter().any(|bits| *bits != 0), "пустой глиф {ch:?}");
        }
    }

    #[test]
    fn extra_table_is_sorted_and_monospaced_cell() {
        assert!(EXTRA_GLYPHS.windows(2).all(|pair| pair[0].0 < pair[1].0));
        assert!(EXTRA_GLYPHS.len() > 60);
    }
}
